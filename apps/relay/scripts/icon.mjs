/**
 * The relay's icon (the Penmoss logo): its favicon, its pages' icon and the icon claude.ai shows
 * beside its connector (`serverInfo.icons`). A Worker can't import images, so this writes the
 * site's `favicon.svg`, and the Mac app's icon at 192 px as a PNG, into `src/icon.gen.ts`;
 * `test/icon.test.ts` fails when the SVG is stale. The PNG is made with macOS's `sips`.
 *
 *   node scripts/icon.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SVG = join(here, '../../../site/public/favicon.svg');
const ICON = join(here, '../../desktop/build/icon.png');
const OUT = join(here, '../src/icon.gen.ts');
export const SIZE = 192;

const scratch = mkdtempSync(join(tmpdir(), 'penmoss-relay-icon-'));
try {
  const png = join(scratch, 'icon.png');
  execFileSync('sips', ['-z', String(SIZE), String(SIZE), ICON, '--out', png], { stdio: 'ignore' });
  writeFileSync(
    OUT,
    `// Generated by scripts/icon.mjs from site/public/favicon.svg and apps/desktop/build/icon.png.\n` +
      `export const ICON_SVG = ${JSON.stringify(readFileSync(SVG, 'utf8').trim())};\n` +
      `export const ICON_PNG_SIZE = ${SIZE};\n` +
      `export const ICON_PNG_BASE64 =\n  ${JSON.stringify(readFileSync(png).toString('base64'))};\n`,
  );
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
console.log(`wrote ${OUT}`);
