export const CATALOGUE: Readonly<Record<EventKind, readonly string[]>> = {
  app: APP_NAMES,
  command: COMMAND_NAMES,
  screen: SCREEN_NAMES,
  dialog: DIALOG_NAMES,
  click: CLICK_NAMES,
  menu: MENU_NAMES,
  setting: SETTING_NAMES,
  firstrun: FIRSTRUN_STEPS,
  feedback: FEEDBACK_NAMES,
  sync: SYNC_NAMES,
  cli: CLI_NAMES,
  tool: TOOL_NAMES,
};

const SETS = new Map(
  Object.entries(CATALOGUE).map(([kind, names]) => [kind, new Set(names)] as const),
);

/** Whether `name` is a known name of `kind`. */
export function isCatalogued(kind: string, name: string): boolean {
  return SETS.get(kind)?.has(name) ?? false;
}
