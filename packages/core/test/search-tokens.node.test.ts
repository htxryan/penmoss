/// <reference types="node" />
/**
 * The client's tokenizer must cut and fold text exactly as D1's FTS5 does
 * (`porter unicode61 remove_diacritics 2`), so a word matches the same notes
 * offline as online (T22). Checked against SQLite itself, for every code
 * point and for real prose. `UPDATE_FTS_UNICODE=1` regenerates the table.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { defaultFold, stemTerm, tokenize } from '../src/search/tokenize';
import { sqliteTerms } from './support/sqlite-fts';

const TABLE_PATH = new URL('../src/search/unicode-table.ts', import.meta.url);

/** Every code point but NUL and surrogates, each between two `x`. */
function everyCodePoint(): number[] {
  const out: number[] = [];
  for (let cp = 1; cp < 0x110000; cp++) if (cp < 0xd800 || cp > 0xdfff) out.push(cp);
  return out;
}

describe('the FTS tokenizer (T22)', () => {
  it('separates and folds every code point as unicode61 with remove_diacritics 2 does', () => {
    const points = everyCodePoint();
    const texts = points.map((cp) => `x${String.fromCodePoint(cp)}x`);
    const expected = sqliteTerms(texts, 'unicode61 remove_diacritics 2');

    if (process.env['UPDATE_FTS_UNICODE'] === '1') {
      const separators: number[] = [];
      const exceptions: string[] = [];
      points.forEach((cp, index) => {
        const terms = expected[index]!;
        if (terms.length !== 1) separators.push(cp);
        else {
          const folded = terms[0]!.slice(1, -1);
          if (folded !== defaultFold(String.fromCodePoint(cp))) {
            exceptions.push(`${cp.toString(36)}:${folded}`);
          }
        }
      });
      const ranges: Array<[number, number]> = [];
      for (const cp of separators) {
        const last = ranges.at(-1);
        if (last && last[1] === cp - 1) last[1] = cp;
        else ranges.push([cp, cp]);
      }
      writeFileSync(
        TABLE_PATH,
        [
          '// Generated by test/search-tokens.node.test.ts (UPDATE_FTS_UNICODE=1); do not edit.',
          "// SQLite's unicode61 tokenizer (Unicode 6.1 tables, remove_diacritics 2), as read from",
          '// SQLite itself: code-point ranges that separate tokens (base 36, `from-to`), and the',
          '// folds that differ from `defaultFold` (`code point:folded`, an empty fold drops it).',
          `export const SEPARATOR_RANGES =\n  '${ranges.map(([a, b]) => (a === b ? a.toString(36) : `${a.toString(36)}-${b.toString(36)}`)).join(',')}';`,
          `export const FOLD_EXCEPTIONS =\n  ${JSON.stringify(exceptions.join(','))};`,
          '',
        ].join('\n'),
      );
    }

    const mismatches: string[] = [];
    points.forEach((cp, index) => {
      const mine = tokenize(texts[index]!, { stem: false }).map((token) => token.term);
      const theirs = expected[index]!;
      if (JSON.stringify(mine) !== JSON.stringify(theirs) && mismatches.length < 20) {
        mismatches.push(
          `U+${cp.toString(16)} sqlite=${JSON.stringify(theirs)} mine=${JSON.stringify(mine)}`,
        );
      }
    });
    expect(mismatches).toEqual([]);
    expect(readFileSync(TABLE_PATH, 'utf8')).toContain('SEPARATOR_RANGES');
  }, 60_000);

  it('stems as SQLite porter does, on English prose and other languages', () => {
    const prose = readFileSync(new URL('../../../docs/decisions.md', import.meta.url), 'utf8');
    const words = [
      ...new Set([
        ...prose.split(/\s+/),
        'running',
        'runner',
        'backups',
        'strategies',
        'café',
        'cafés',
        'naïve',
        'naïves',
        'straßen',
        'großers',
        'fußballs',
        'niños',
        'mañana',
        'Ölmühlen',
        'мамы',
        'книгами',
        'ελληνικά',
        'Ϳs',
        '日本語',
        'x'.repeat(63) + 'ing',
        'x'.repeat(70) + 'ing',
        'é'.repeat(32) + 'ing',
        'ab',
        'és',
        'éé',
      ]),
    ];
    const expected = sqliteTerms(words);
    const mismatches: string[] = [];
    words.forEach((word, index) => {
      const mine = tokenize(word).map((token) => token.term);
      if (JSON.stringify(mine) !== JSON.stringify(expected[index])) {
        mismatches.push(
          `${word}: sqlite=${JSON.stringify(expected[index])} mine=${JSON.stringify(mine)}`,
        );
      }
    });
    expect(mismatches).toEqual([]);
    expect(words.length).toBeGreaterThan(1000);
  });

  it('gives every folded word back whole behind a key, as notes_words stores it (A680)', () => {
    const words = new Set<string>();
    for (const cp of everyCodePoint()) {
      for (const { term } of tokenize(`x${String.fromCodePoint(cp)}x`, { stem: false })) {
        words.add(term);
      }
    }
    const list = [...words];
    // A workspace key is 13 base-36 characters (apps/server/src/search/words.ts).
    const keyed = list.map((word) => `0k3y5x9a1b2c3${word}`);
    const stored = sqliteTerms(keyed, 'unicode61 remove_diacritics 2');
    const changed = keyed.filter((text, i) => JSON.stringify(stored[i]) !== JSON.stringify([text]));
    expect(changed.slice(0, 20)).toEqual([]);
    expect(list.length).toBeGreaterThan(1000);
  }, 60_000);

  it('keeps the first two letters of a word through the porter step (MIN_COMPLETION_LENGTH)', () => {
    const prose = readFileSync(new URL('../../../docs/decisions.md', import.meta.url), 'utf8');
    const words = [...new Set(tokenize(prose, { stem: false }).map((token) => token.term))];
    // A two-letter prefix needs no completions: no word's stem drops or changes its first two.
    const cut = words.filter(
      (word) => word.length >= 2 && !stemTerm(word).startsWith(word.slice(0, 2)),
    );
    expect(cut).toEqual([]);
    expect(words.length).toBeGreaterThan(3000);
  });

  it('keeps where each token is in the text, for snippets', () => {
    expect(tokenize('Backup strategy: the git mirror (2026)!')).toEqual([
      { term: 'backup', start: 0, end: 6 },
      { term: 'strategi', start: 7, end: 15 },
      { term: 'the', start: 17, end: 20 },
      { term: 'git', start: 21, end: 24 },
      { term: 'mirror', start: 25, end: 31 },
      { term: '2026', start: 33, end: 37 },
    ]);
    expect(tokenize('Ça va 👋 naïve 😀x')).toEqual([
      { term: 'ca', start: 0, end: 2 },
      { term: 'va', start: 3, end: 5 },
      { term: 'naiv', start: 9, end: 14 },
      { term: 'x', start: 17, end: 18 },
    ]);
    expect(stemTerm('running')).toBe('run');
  });
});
